    fn fixture_config_with_deps(packages: Vec<(&str, bool, Vec<&str>)>) -> Config {
        let mut map = BTreeMap::new();
        for (name, enabled, deps) in packages {
            map.insert(
                name.to_string(),
                PackageConfig {
                    enabled,
                    depends_on: deps.into_iter().map(String::from).collect(),
                    ..Default::default()
                },
            );
        }
        Config {
            packages: map,
            ..Default::default()
        }
    }

