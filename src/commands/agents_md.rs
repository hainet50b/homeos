use crate::Cli;
use clap::{Arg, Command, CommandFactory};
use std::fs;
use std::io::Write;
use std::path::Path;

const TEMPLATE: &str = include_str!("../../templates/AGENTS.md.tmpl");

pub fn run() -> Result<(), Box<dyn std::error::Error>> {
    run_to(&mut std::io::stdout())
}

fn run_to<W: Write>(writer: &mut W) -> Result<(), Box<dyn std::error::Error>> {
    let rendered = render();
    writer.write_all(rendered.as_bytes())?;
    Ok(())
}

/// Render AGENTS.md and write it to `<data_dir>/AGENTS.md`. Also place CLAUDE.md
/// alongside so Claude Code's ancestor scan finds the same content: on Unix
/// CLAUDE.md is a symlink to AGENTS.md; on Windows it is a copy of the rendered
/// content because Windows symlinks require elevated privileges.
pub fn write_files(data_dir: &Path) -> Result<(), Box<dyn std::error::Error>> {
    let rendered = render();
    let agents_md = data_dir.join("AGENTS.md");
    fs::write(&agents_md, &rendered)?;

    let claude_md = data_dir.join("CLAUDE.md");
    if claude_md.symlink_metadata().is_ok() {
        fs::remove_file(&claude_md)?;
    }
    #[cfg(unix)]
    {
        std::os::unix::fs::symlink("AGENTS.md", &claude_md)?;
    }
    #[cfg(windows)]
    {
        fs::write(&claude_md, &rendered)?;
    }

    Ok(())
}

fn render() -> String {
    let version = env!("CARGO_PKG_VERSION");
    let commands_reference = build_commands_reference();
    TEMPLATE
        .replace("{{ version }}", version)
        .replace("{{ commands_reference }}", &commands_reference)
}

fn build_commands_reference() -> String {
    let cmd = Cli::command();
    let mut output = String::new();
    walk_subcommands(&cmd, "homeos", &mut output);
    output.trim_end().to_string()
}

fn walk_subcommands(cmd: &Command, path: &str, output: &mut String) {
    for sub in cmd.get_subcommands() {
        let sub_name = sub.get_name();
        if sub_name == "help" {
            continue;
        }
        let sub_path = format!("{path} {sub_name}");
        let has_nested_leaves = sub.get_subcommands().any(|s| s.get_name() != "help");
        if has_nested_leaves {
            walk_subcommands(sub, &sub_path, output);
        } else {
            emit_leaf_entry(sub, &sub_path, output);
        }
    }
}

fn emit_leaf_entry(cmd: &Command, path: &str, output: &mut String) {
    output.push_str(&format!("### `{path}`\n\n"));
    if let Some(about) = cmd.get_about() {
        output.push_str(&format!("{about}\n\n"));
    }
    let args: Vec<&Arg> = cmd
        .get_arguments()
        .filter(|a| {
            !a.is_hide_set()
                && !a.is_global_set()
                && a.get_id().as_str() != "help"
                && a.get_id().as_str() != "version"
        })
        .collect();
    if !args.is_empty() {
        for arg in args {
            output.push_str(&format_arg_entry(arg));
            output.push('\n');
        }
        output.push('\n');
    }
}

fn format_arg_entry(arg: &Arg) -> String {
    let identifier = if arg.is_positional() {
        format!("<{}>", arg.get_id().as_str().to_uppercase())
    } else if let Some(long) = arg.get_long() {
        format!("--{long}")
    } else if let Some(short) = arg.get_short() {
        format!("-{short}")
    } else {
        arg.get_id().as_str().to_string()
    };
    let help = arg.get_help().map(|h| h.to_string()).unwrap_or_default();
    if help.is_empty() {
        format!("- `{identifier}`")
    } else {
        format!("- `{identifier}` — {help}")
    }
}

#[cfg(test)]
