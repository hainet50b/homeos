    #[test]
    fn test_render_substitutes_version_marker() {
        // Arrange
        let expected_marker = format!("<!-- generated by homeos {} -->", env!("CARGO_PKG_VERSION"));

        // Act
        let rendered = render();

        // Assert
        assert!(
            rendered.starts_with(&expected_marker),
            "expected marker on first line, got: {:?}",
            rendered.lines().next()
        );
        assert!(!rendered.contains("{{ version }}"));
    }

